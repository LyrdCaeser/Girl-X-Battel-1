-- GXB2 Offline: account/device/sync metadata schema.
-- Apply only to the dedicated `gxb2_offline` database, never to the Online project.
-- The authoritative gameplay save and downloaded assets remain on the user's device.
-- This migration stores identity and synchronization metadata only; no save payloads or assets.

BEGIN;

CREATE TABLE IF NOT EXISTS public.accounts (
    account_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username TEXT NOT NULL,
    email TEXT,
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'suspended', 'deleted')),
    -- Password credentials are optional for accounts authenticated by an external provider.
    -- Store only a salted password hash; never store plaintext passwords.
    password_hash BYTEA,
    password_salt BYTEA,
    password_kdf TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT accounts_username_nonempty CHECK (length(btrim(username)) BETWEEN 1 AND 64),
    CONSTRAINT accounts_email_nonempty CHECK (email IS NULL OR length(btrim(email)) BETWEEN 3 AND 320),
    CONSTRAINT accounts_password_fields_paired CHECK (
        (password_hash IS NULL AND password_salt IS NULL AND password_kdf IS NULL)
        OR
        (password_hash IS NOT NULL AND password_salt IS NOT NULL
            AND password_kdf IS NOT NULL AND length(btrim(password_kdf)) > 0)
    ),
    CONSTRAINT accounts_deleted_at_consistent CHECK (
        (status = 'deleted' AND deleted_at IS NOT NULL)
        OR (status <> 'deleted' AND deleted_at IS NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS accounts_username_lower_uq
    ON public.accounts (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS accounts_email_lower_uq
    ON public.accounts (lower(email)) WHERE email IS NOT NULL;
CREATE INDEX IF NOT EXISTS accounts_status_created_idx
    ON public.accounts (status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.devices (
    device_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    account_id UUID NOT NULL REFERENCES public.accounts(account_id) ON DELETE CASCADE,
    -- Random app-install ID generated by the client; do not use hardware identifiers.
    installation_id UUID NOT NULL,
    platform TEXT NOT NULL CHECK (platform IN ('ios', 'android')),
    device_label TEXT,
    app_version TEXT NOT NULL DEFAULT '',
    save_schema_version INTEGER NOT NULL DEFAULT 1 CHECK (save_schema_version > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_sync_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    UNIQUE (account_id, installation_id),
    -- Composite key supports a foreign key that ensures sync metadata cannot
    -- associate an account with another account's device.
    UNIQUE (account_id, device_id),
    CONSTRAINT devices_label_length CHECK (device_label IS NULL OR length(device_label) <= 80),
    CONSTRAINT devices_app_version_length CHECK (length(app_version) <= 64)
);

CREATE INDEX IF NOT EXISTS devices_account_last_seen_idx
    ON public.devices (account_id, last_seen_at DESC);
CREATE INDEX IF NOT EXISTS devices_active_account_idx
    ON public.devices (account_id, device_id) WHERE revoked_at IS NULL;

CREATE TABLE IF NOT EXISTS public.sync_metadata (
    sync_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    account_id UUID NOT NULL,
    device_id UUID NOT NULL,
    -- Allows future independent sync streams without mixing gameplay save and settings.
    stream_key TEXT NOT NULL DEFAULT 'game-save',
    local_revision BIGINT NOT NULL DEFAULT 0 CHECK (local_revision >= 0),
    acknowledged_local_revision BIGINT NOT NULL DEFAULT 0 CHECK (acknowledged_local_revision >= 0),
    base_cloud_revision BIGINT NOT NULL DEFAULT 0 CHECK (base_cloud_revision >= 0),
    cloud_revision BIGINT NOT NULL DEFAULT 0 CHECK (cloud_revision >= 0),
    save_schema_version INTEGER NOT NULL DEFAULT 1 CHECK (save_schema_version > 0),
    checksum_sha256 TEXT,
    last_mutation_id UUID,
    sync_status TEXT NOT NULL DEFAULT 'never'
        CHECK (sync_status IN ('never', 'pending', 'synced', 'conflict', 'error')),
    last_sync_at TIMESTAMPTZ,
    last_error_code TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT sync_metadata_device_account_fk
        FOREIGN KEY (account_id, device_id)
        REFERENCES public.devices (account_id, device_id) ON DELETE CASCADE,
    CONSTRAINT sync_metadata_stream_nonempty CHECK (length(btrim(stream_key)) BETWEEN 1 AND 64),
    CONSTRAINT sync_metadata_ack_not_ahead CHECK (acknowledged_local_revision <= local_revision),
    CONSTRAINT sync_metadata_checksum_sha256 CHECK (
        checksum_sha256 IS NULL OR checksum_sha256 ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT sync_metadata_error_code_length CHECK (
        last_error_code IS NULL OR length(last_error_code) <= 120
    ),
    UNIQUE (account_id, device_id, stream_key)
);

CREATE INDEX IF NOT EXISTS sync_metadata_account_updated_idx
    ON public.sync_metadata (account_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS sync_metadata_pending_idx
    ON public.sync_metadata (sync_status, updated_at)
    WHERE sync_status IN ('pending', 'conflict', 'error');

COMMENT ON TABLE public.accounts IS
    'Offline edition account identity metadata; gameplay progress remains on-device.';
COMMENT ON TABLE public.devices IS
    'Registered iOS/Android app installations; installation_id is random and not a hardware ID.';
COMMENT ON TABLE public.sync_metadata IS
    'Per-device sync revisions/checksum/status only; contains no save payload or downloadable assets.';

COMMIT;
